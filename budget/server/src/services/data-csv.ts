export interface ImportReport {
  dryRun: boolean;
  /** Rows that were (or, in a dry run, would be) imported. */
  imported: number;
  /** Rows left out on purpose: "à confirmer" placeholders are regenerated by the app itself. */
  skipped: number;
  errors: { line: number; message: string }[];
}

const MAX_ROWS = 5000;

function tableFrom(text: string, required: string[]): ReturnType<typeof toTable> {
  let rows: string[][];
  try {
    rows = parseCsv(text);
  } catch (err) {
    throw new HttpError(400, 'csv_invalid', err instanceof Error ? err.message : 'CSV illisible');
  }
  const table = toTable(rows);
  const missing = required.filter((c) => !table.header.includes(c));
  if (missing.length > 0) {
    throw new HttpError(400, 'csv_invalid', `Colonnes manquantes : ${missing.join(', ')}`);
  }
  if (table.rows.length > MAX_ROWS) throw new HttpError(400, 'csv_too_large', `Maximum ${MAX_ROWS} lignes par import`);
  return table;
}

// ------------------------------------------------------------------ expenses

function splitLabel(e: { splitMode: string; customBp: Record<string, number> | null; singleId: string | null }, people: PersonDto[]): string {
  if (e.splitMode === 'income') return 'revenus';
  if (e.splitMode === 'equal') return '50/50';
  if (e.splitMode === 'single') return `100% ${people.find((p) => p.id === e.singleId)?.name ?? ''}`.trim();
  const first = people[0];
  const share = first ? (e.customBp?.[first.id] ?? 5000) / 100 : 50;
  return `${share}/${100 - share}`;
}

export function exportExpensesCsv(ctx: AppContext, month?: string): string {
  const people = listPeople(ctx.db);
  const names = new Map(people.map((p) => [p.id, p.name]));
  const categories = new Map(getCatalog(ctx.db).flatMap((g) => g.categories.map((c) => [c.id, c] as const)));
  const rows: string[][] = [['date', 'montant', 'categorie', 'sous_ligne', 'paye_par', 'repartition', 'tags', 'note', 'statut']];
  for (const e of listExpenses(ctx.db, month ? { month } : {}, 1_000_000).reverse()) {
    const cat = categories.get(e.categoryId);
    rows.push([
      e.date,
      formatAmountCsv(e.amountCents),
      cat?.name ?? '',
      cat?.subcategories.find((s) => s.id === e.subcategoryId)?.name ?? '',
      names.get(e.payerId) ?? '',
      splitLabel(e, people),
      e.tags.join('|'),
      e.note,
      e.status === 'pending' ? 'à confirmer' : 'confirmée',
    ]);
  }
  return formatCsv(rows);
}

function parseSplit(raw: string, people: PersonDto[], fallback: 'income' | 'equal'): Pick<ExpenseInput, 'splitMode' | 'singleId' | 'customBp'> | string {
  const value = normalizeName(raw);
  if (value === '') return { splitMode: fallback, singleId: null, customBp: null };
  if (['revenus', 'income', 'prorata', 'au prorata'].includes(value)) return { splitMode: 'income', singleId: null, customBp: null };
  if (['50/50', '50-50', 'equal', 'egal', 'moitie'].includes(value)) return { splitMode: 'equal', singleId: null, customBp: null };

  const single = /^(?:100\s*%|perso|personnel)[\s:]+(.+)$/.exec(value);
  if (single) {
    const person = people.find((p) => normalizeName(p.name) === single[1]);
    return person ? { splitMode: 'single', singleId: person.id, customBp: null } : `Personne inconnue dans la répartition : ${raw}`;
  }
  const pct = /^(\d+(?:[.,]\d+)?)\s*\/\s*(\d+(?:[.,]\d+)?)$/.exec(value);
  if (pct && people.length === 2) {
    const a = Math.round(Number((pct[1] as string).replace(',', '.')) * 100);
    const b = Math.round(Number((pct[2] as string).replace(',', '.')) * 100);
    if (a + b !== 10000) return `Les pourcentages doivent faire 100 % : ${raw}`;
    return { splitMode: 'custom', singleId: null, customBp: { [(people[0] as PersonDto).id]: a, [(people[1] as PersonDto).id]: b } };
  }
  return `Répartition non reconnue : ${raw} (revenus, 50/50, 100% Prénom ou 60/40)`;
}

/**
 * Imports expenses. All-or-nothing: if any row is invalid nothing is written and every problem is
 * reported with its line number, so the file can be fixed and retried.
 */
export function importExpensesCsv(ctx: AppContext, text: string, opts: { dryRun: boolean; createdBy: string | null }): ImportReport {
  const { db } = ctx;
  const people = listPeople(db);
  const table = tableFrom(text, ['date', 'montant', 'categorie']);
  const catalog = getCatalog(db).flatMap((g) => g.categories.filter((c) => !c.archived));
  const defaultSplit = getSettings(db).defaultSplitMode;

  const errors: ImportReport['errors'] = [];
  const parsed: { line: number; input: ExpenseInput }[] = [];

  let skipped = 0;
  for (const { line, values } of table.rows) {
    const fail = (message: string): void => void errors.push({ line, message });
    if (normalizeName(values.statut ?? '') === 'a confirmer') {
      skipped += 1;
      continue;
    }
    const date = parseDateFlexible(values.date ?? '');
    if (!date || !isIsoDate(date)) {
      fail(`Date invalide : « ${values.date ?? ''} »`);
      continue;
    }
    const amount = parseAmountCents(values.montant ?? '');
    if (amount === null || amount <= 0) {
      fail(`Montant invalide : « ${values.montant ?? ''} »`);
      continue;
    }
    const category = catalog.find((c) => normalizeName(c.name) === normalizeName(values.categorie ?? ''));
    if (!category) {
      fail(`Catégorie inconnue : « ${values.categorie ?? ''} »`);
      continue;
    }
    let subcategoryId: string | null = null;
    if (values.sous_ligne) {
      const sub = category.subcategories.find((s) => !s.archived && normalizeName(s.name) === normalizeName(values.sous_ligne ?? ''));
      if (!sub) {
        fail(`Sous-ligne inconnue pour ${category.name} : « ${values.sous_ligne} »`);
        continue;
      }
      subcategoryId = sub.id;
    }
    const payerName = values.paye_par ?? '';
    const payer = payerName ? people.find((p) => normalizeName(p.name) === normalizeName(payerName)) : people[0];
    if (!payer) {
      fail(`Payeur inconnu : « ${payerName} »`);
      continue;
    }
    const split = parseSplit(values.repartition ?? '', people, defaultSplit);
    if (typeof split === 'string') {
      fail(split);
      continue;
    }
    parsed.push({
      line,
      input: {
        date,
        amountCents: amount,
        categoryId: category.id,
        subcategoryId,
        payerId: payer.id,
        ...split,
        tags: (values.tags ?? '').split(/[|,]/).map((t) => t.trim()).filter(Boolean),
        note: values.note ?? '',
      },
    });
  }

  if (errors.length > 0) return { dryRun: opts.dryRun, imported: 0, skipped, errors };
  if (opts.dryRun) return { dryRun: true, imported: parsed.length, skipped, errors: [] };

  try {
    db.transaction(() => {
      for (const { line, input } of parsed) {
        try {
          createExpense(db, input, { createdBy: opts.createdBy ?? 'import' });
        } catch (err) {
          throw Object.assign(new Error(err instanceof Error ? err.message : 'Erreur'), { line });
        }
      }
    })();
  } catch (err) {
    const line = (err as { line?: number }).line ?? 0;
    return { dryRun: false, imported: 0, skipped, errors: [{ line, message: err instanceof Error ? err.message : 'Erreur' }] };
  }
  return { dryRun: false, imported: parsed.length, skipped, errors: [] };
}

// ------------------------------------------------------------------ savings

export function exportSavingsCsv(ctx: AppContext): string {
  const accounts = new Map(ctx.db.prepare('SELECT id, name FROM savings_accounts').all().map((a) => [(a as { id: string }).id, (a as { name: string }).name]));
  const entries = ctx.db
    .prepare('SELECT account_id, month, contribution_cents, balance_cents, note FROM savings_entries ORDER BY month, account_id')
    .all() as { account_id: string; month: string; contribution_cents: number; balance_cents: number | null; note: string }[];
  const rows: string[][] = [['compte', 'mois', 'versement', 'solde', 'note']];
  for (const e of entries) {
    rows.push([
      accounts.get(e.account_id) ?? '',
      e.month,
      formatAmountCsv(e.contribution_cents),
      e.balance_cents === null ? '' : formatAmountCsv(e.balance_cents),
      e.note,
    ]);
  }
  return formatCsv(rows);
}

function parseMonthFlexible(raw: string): string | null {
  const value = raw.trim();
  if (isMonthKey(value)) return value;
  const fr = /^(\d{1,2})[/.](\d{4})$/.exec(value);
  if (fr) {
    const month = `${fr[2]}-${(fr[1] as string).padStart(2, '0')}`;
    return isMonthKey(month) ? month : null;
  }
  return null;
}

/** Imports monthly savings entries (upserts by account and month). All-or-nothing, like expenses. */
export function importSavingsCsv(ctx: AppContext, text: string, opts: { dryRun: boolean }): ImportReport {
  const { db } = ctx;
  const table = tableFrom(text, ['compte', 'mois', 'versement']);
  const accounts = db.prepare('SELECT id, name, archived FROM savings_accounts').all() as { id: string; name: string; archived: number }[];

  const errors: ImportReport['errors'] = [];
  const parsed: Parameters<typeof upsertEntry>[1][] = [];
  for (const { line, values } of table.rows) {
    const fail = (message: string): void => void errors.push({ line, message });
    const account = accounts.find((a) => normalizeName(a.name) === normalizeName(values.compte ?? ''));
    if (!account) {
      fail(`Compte inconnu : « ${values.compte ?? ''} » (créez-le d'abord dans l'app)`);
      continue;
    }
    if (account.archived === 1) {
      fail(`Compte archivé : ${account.name}`);
      continue;
    }
    const month = parseMonthFlexible(values.mois ?? '');
    if (!month) {
      fail(`Mois invalide : « ${values.mois ?? ''} » (AAAA-MM)`);
      continue;
    }
    const contribution = parseAmountCents(values.versement ?? '0');
    if (contribution === null) {
      fail(`Versement invalide : « ${values.versement ?? ''} »`);
      continue;
    }
    const balanceRaw = values.solde ?? '';
    const balance = balanceRaw === '' ? null : parseAmountCents(balanceRaw);
    if (balanceRaw !== '' && (balance === null || balance < 0)) {
      fail(`Solde invalide : « ${balanceRaw} »`);
      continue;
    }
    parsed.push({ accountId: account.id, month, contributionCents: contribution, balanceCents: balance, note: values.note ?? '' });
  }

  if (errors.length > 0) return { dryRun: opts.dryRun, imported: 0, skipped: 0, errors };
  if (!opts.dryRun) db.transaction(() => parsed.forEach((p) => upsertEntry(db, p)))();
  return { dryRun: opts.dryRun, imported: parsed.length, skipped: 0, errors: [] };
}
